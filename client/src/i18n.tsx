export type Key = keyof typeof dict;

const Ctx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: "en", setLang: () => {} });

function initial(): Lang {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "de" || saved === "en") return saved;
  } catch { /* private mode */ }
  return navigator.language.toLowerCase().startsWith("de") ? "de" : "en";
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initial);
  const setLang = (l: Lang) => { setLangState(l); try { localStorage.setItem("lang", l); } catch { /* ignore */ } document.documentElement.lang = l; };
  return <Ctx.Provider value={{ lang, setLang }}>{children}</Ctx.Provider>;
}

export function useLang() { return useContext(Ctx); }

export function useT() {
  const { lang } = useContext(Ctx);
  return (key: Key, vars?: Record<string, string | number>) => {
    let s: string = dict[key][lang === "de" ? 1 : 0];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export function LangSwitch({ light = false }: { light?: boolean }) {
  const { lang, setLang } = useLang();
  const cls = (l: Lang) => `px-2 py-1 text-xs font-bold rounded-md ${lang === l ? (light ? "bg-white/15 text-white" : "bg-ink text-white") : (light ? "text-white/60 hover:text-white" : "text-mute hover:text-ink")}`;
  return (
    <div className="inline-flex gap-0.5" role="group" aria-label="Language">
      <button className={cls("de")} onClick={() => setLang("de")}>DE</button>
      <button className={cls("en")} onClick={() => setLang("en")}>EN</button>
    </div>
  );
}
